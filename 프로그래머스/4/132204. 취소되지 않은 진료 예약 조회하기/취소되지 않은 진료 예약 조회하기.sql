SELECT J.APNT_NO,P.PT_NAME,J.PT_NO,J.MCDP_CD,J.DR_NAME, J.APNT_YMD
FROM PATIENT P
JOIN (
    SELECT A.APNT_NO, A.PT_NO,A.MCDP_CD,D.DR_NAME, A.APNT_YMD
    FROM APPOINTMENT A
    JOIN DOCTOR D
    ON A.MDDR_ID = D.DR_ID
    WHERE A.MCDP_CD = "CS" AND A.APNT_CNCL_YN = "N" AND SUBSTR(A.APNT_YMD,1,10)='2022-04-13'
) J
ON P.PT_NO = J.PT_NO
ORDER BY J.APNT_YMD 
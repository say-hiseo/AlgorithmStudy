WITH CS AS (
    SELECT NAME, S.CODE
    FROM SKILLCODES S
    WHERE NAME = 'C#' OR NAME = 'Python'
),
FSUM AS (
    SELECT SUM(S.CODE) AS FS
    FROM SKILLCODES S
    GROUP BY CATEGORY HAVING CATEGORY = 'Front End'
)
SELECT DD.GRADE, DD.ID, D.EMAIL
FROM DEVELOPERS D
JOIN (
    SELECT CASE WHEN SKILL_CODE & (SELECT FS FROM FSUM) > 0 AND SKILL_CODE & (SELECT CS.CODE FROM CS WHERE NAME = 'Python') > 0 THEN 'A'
    WHEN SKILL_CODE & (SELECT CS.CODE FROM CS WHERE NAME = 'C#') > 0 THEN 'B'
    WHEN SKILL_CODE & (SELECT FS FROM FSUM) > 0 THEN 'C' END AS GRADE, ID
    FROM DEVELOPERS
) DD ON D.ID = DD.ID
WHERE GRADE IS NOT NULL
ORDER BY GRADE, ID;
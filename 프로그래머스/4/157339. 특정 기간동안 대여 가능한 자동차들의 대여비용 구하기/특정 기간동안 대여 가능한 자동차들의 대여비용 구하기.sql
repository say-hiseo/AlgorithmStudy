#  자동차 종류가 '세단' 또는 'SUV' 인 자동차 중 
# 2022년 11월 1일부터 2022년 11월 30일까지 대여 가능하고 
# 30일간의 대여 금액이 50만원 이상 200만원 미만인 자동차
WITH POSSIBLE_CAR AS(
    SELECT C.CAR_ID, C.CAR_TYPE, C.DAILY_FEE
    FROM CAR_RENTAL_COMPANY_CAR C
    WHERE C.CAR_ID NOT IN (
        SELECT CAR_ID FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY 
        GROUP BY CAR_ID 
        HAVING MAX(END_DATE)>'2022-11-01'
    ) AND C.CAR_TYPE IN ('세단', 'SUV')
), 
PRICE AS (
    SELECT CAR_TYPE, DISCOUNT_RATE
    FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
    WHERE CAR_TYPE IN ('세단', 'SUV') AND DURATION_TYPE = '30일 이상'
)


SELECT PC.CAR_ID,PC.CAR_TYPE, FLOOR(PC.DAILY_FEE*((100-P.DISCOUNT_RATE)/100)*30) AS FEE
FROM POSSIBLE_CAR PC
JOIN PRICE P ON PC.CAR_TYPE=P.CAR_TYPE
WHERE FLOOR(PC.DAILY_FEE*((100-P.DISCOUNT_RATE)/100)*30) >= 500000 AND FLOOR(PC.DAILY_FEE*((100-P.DISCOUNT_RATE)/100)*30) <= 2000000
ORDER BY FEE DESC, CAR_TYPE, CAR_ID DESC;
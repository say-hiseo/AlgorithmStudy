SELECT E.EMP_NO,E.EMP_NAME, 
    CASE WHEN G.SA>= 96 THEN 'S'
    WHEN G.SA >= 90 THEN 'A'
    WHEN G.SA >= 80 THEN 'B'
    ELSE 'C' END AS GRADE,
    CASE WHEN G.SA>= 96 THEN SAL*0.2
    WHEN G.SA >= 90 THEN SAL*0.15
    WHEN G.SA >= 80 THEN SAL*0.1
    ELSE 0 END AS BONUS
FROM HR_EMPLOYEES E
JOIN (
    SELECT EMP_NO, AVG(SCORE) AS SA
    FROM HR_GRADE 
    GROUP BY EMP_NO
) G
ON E.EMP_NO=G.EMP_NO

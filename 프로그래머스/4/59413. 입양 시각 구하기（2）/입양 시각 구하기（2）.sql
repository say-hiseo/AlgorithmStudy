WITH RECURSIVE HOURS AS (
    SELECT 0 AS HOUR
    UNION ALL
    SELECT HOUR+1
    FROM HOURS
    WHERE HOUR<23
)

SELECT H.HOUR, IFNULL(O.COUNT,0)
FROM HOURS H
LEFT JOIN (
    SELECT HOUR(DATETIME) AS HOUR, COUNT(*) AS COUNT
    FROM ANIMAL_OUTS 
    GROUP BY HOUR
) O
ON H.HOUR=O.HOUR
ORDER BY HOUR
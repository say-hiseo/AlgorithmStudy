WITH P AS (
    SELECT CAR_TYPE,DURATION_TYPE, DISCOUNT_RATE
    FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
    WHERE CAR_TYPE = '트럭'
),
J AS (
    SELECT H.HISTORY_ID, C.CAR_TYPE, DATEDIFF(END_DATE,START_DATE)+1 AS DURATION, CASE WHEN DATEDIFF(END_DATE,START_DATE)+1 >= 90 THEN '90일 이상'
    WHEN DATEDIFF(END_DATE,START_DATE)+1 >= 30 THEN '30일 이상'
    WHEN DATEDIFF(END_DATE,START_DATE)+1 >= 7 THEN '7일 이상' END AS DURATION_TYPE, C.DAILY_FEE
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY H
    JOIN CAR_RENTAL_COMPANY_CAR C
    ON C.CAR_ID = H.CAR_ID
    WHERE C.CAR_TYPE = '트럭'
)

SELECT J.HISTORY_ID, FLOOR(J.DAILY_FEE * ((100-IFNULL(P.DISCOUNT_RATE,0)) / 100) * J.DURATION) AS FEE
FROM J
LEFT JOIN P ON J.DURATION_TYPE = P.DURATION_TYPE
ORDER BY FEE DESC, J.HISTORY_ID DESC
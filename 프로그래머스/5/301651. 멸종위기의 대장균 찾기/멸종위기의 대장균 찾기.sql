WITH RECURSIVE C AS(
    SELECT ID, 1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E.ID, C.GENERATION+1
    FROM ECOLI_DATA E
    JOIN C ON E.PARENT_ID = C.ID
)

SELECT COUNT(*) AS COUNT , GENERATION
FROM C
WHERE NOT EXISTS(SELECT 1 FROM ECOLI_DATA CH WHERE CH.PARENT_ID=C.ID)
GROUP BY GENERATION
ORDER BY GENERATION
WITH HG AS (
    SELECT EMP_NO, SUM(SCORE) AS MS
    FROM HR_GRADE
    GROUP BY EMP_NO
)
    
SELECT HG.MS AS SCORE,HE.EMP_NO,HE.EMP_NAME,HE.POSITION,HE.EMAIL
FROM HR_EMPLOYEES HE
JOIN HG ON HG.EMP_NO = HE.EMP_NO
WHERE HE.EMP_NO IN (
    SELECT EMP_NO 
    FROM HG
    WHERE MS = (SELECT MAX(MS) FROM HG)
)
